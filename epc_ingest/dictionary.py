"""Generate docs/DATA_DICTIONARY.md from the output schema, the registry and the manifest.

    python -m epc_ingest.dictionary
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from .columns import SCHEMA
from .core.output import load_schema
from .core.sources import ROOT, load_registry
from .sql_check import declared_type

OUT = ROOT / "docs" / "DATA_DICTIONARY.md"

OBSERVED_CODES = [
    "`-1` in `LOW_ENERGY_FIXED_LIGHT_COUNT` and `FLAT_TOP_STOREY`.",
    "`00` to `20`, zero-padded, in `FLAT_TOP_STOREY`, which is why it stays text.",
    "`N`, `Y`, `false` and `true` mixed in `SOLAR_WATER_HEATING_FLAG`.",
    "Negative values in the three `IMPACT_*_INSULATION` columns: they are reductions.",
    "Codes such as `00EM` in `LOCAL_AUTHORITY_LABEL` in a few rows.",
    "`FLOOR_HEIGHT` up to 2,550, `NUMBER_HABITABLE_ROOMS` up to 99, `NUMBER_OPEN_FIREPLACES` up to 100, `SPACE_HEATING_DEMAND` from -8,653,797 to 1,751,944,128.",
    "Efficiency and impact ratings above 100 (a SAP rating runs 1 to 100), up to 21,277 and 38,128.",
    "`TOTAL_FLOOR_AREA` is 0 in every 2008 and 2009 row.",
    "`DATA_ZONE` holds `00Q` and `00R` in a few hundred 2026 rows and is empty in 4 to 12 percent of rows from 2015; `DATA_ZONE_2011` holds `NA` in some rows and is empty in 4 to 8 percent from 2021.",
    "`ADDENDUM_TEXT` is empty in every row. `TYPE_OF_ASSESSMENT` is empty in 7,490 rows from 2023.",
    "Five publisher's labels carry the replacement character U+FFFD (\ufffd) where the publisher's export lost a `²` or a `£`; the labels are kept as the file prints them, and the publication note gives the intended character.",
    "Twenty-eight columns hold `|`-separated lists (`IMPROVEMENTS`, `ALTERNATIVE_IMPROVEMENTS`, `LZC_ENERGY_SOURCES`, `PHOTO_SUPPLY`, and the element description and rating columns).",
    "Seven cells carry a trailing newline inside the quotes (six in `BUILDING_REFERENCE_NUMBER`, one in `ADDRESS1`); six `ADDRESS1` cells contain a double quote. They are kept as published; the derived `uprn_sepcr` is trimmed.",
]


def render() -> str:
    schema = load_schema(SCHEMA)
    registry = load_registry()
    manifest_path = ROOT / "results" / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.is_file() else None
    lines = [f"# Data dictionary: `{schema['table']}`, schema `{schema['version']}`", "",
             "One row per published domestic Energy Performance Certificate in Scotland, superseded certificates",
             "included. Key: `epc_release`, `source_year`, `source_row`. Three groups of columns in this order: the key",
             "and provenance added by the build, the 107 published columns as text exactly as published under the",
             "publisher's names, and the derived columns, each a typed copy of one published column by one rule.",
             "Generated by `python -m epc_ingest.dictionary`; do not edit by hand.", ""]
    if manifest:
        lines += [f"Current build: release {manifest['epc_release']}, {manifest['csv']['rows']:,} rows; {manifest['parquet']['columns']} columns in the Parquet, "
                  f"{manifest['csv']['columns']} in the CSV; built {manifest['built_at'][:19]}Z.",
                  f"CSV SHA256 `{manifest['csv']['sha256']}`, Parquet SHA256 `{manifest['parquet']['sha256']}`.", ""]
    lines += ["## Conventions", "",
              f"- Publisher: {registry.publisher}. Licence: {registry.licence}",
              "- `HISTORIC = True` means the certificate has been superseded by a later one for the same property, not that it has expired. A certificate is valid for ten years.",
              "- The published columns are never NULL: an empty cell is the empty string, as published. The derived columns are NULL only where the dictionary below says so.",
              "- Join by `uprn_osg` as an integer, never as text: a cohort UPRN padded to 12 digits matches once both sides are bigint. The published `OSG_REFERENCE_NUMBER` text is provenance only.",
              "- Most dwellings in Scotland have never had a certificate: about 1.9 million UPRNs appear here against about 2.7 million dwellings. A cohort row with no match is `uprn_not_in_epc`, not an error.",
              "- Every column of the Parquet is in the CSV and the SQL table, the three address lines included (`epc_ingest/export_contract.yaml`, decision `address-lines-loaded`); nothing built leaves the safe haven.",
              "- Column names are case-sensitive in the Parquet; in SQL Server they are compared under the database collation, which is why no derived name equals a published name in another case.", "",
              "## Columns", "", "| # | Column | Group | SQL type | Null | Publisher's label | Description |", "| ---: | --- | --- | --- | --- | --- | --- |"]
    for i, f in enumerate(schema["fields"], 1):
        label = f.get("label", "")
        lines.append(f"| {i} | `{f['name']}` | {f['group']} | {declared_type(f)} | {'yes' if f['nullable'] else 'no'} | {label} | {f['description']} |")
    lines += ["", "## Values that are codes, not measurements", "",
              "Found in the profile of release 2026Q2 and kept as published; none is documented by the publisher.", ""]
    lines += [f"- {c}" for c in OBSERVED_CODES]
    lines += ["", "## Sources", "", f"Release `{registry.epc_release}`, extracted from the register on {registry.release['extracted_from_register']}, "
              f"downloaded {registry.release['downloaded']} from {registry.publisher_pages['catalogue']}.", "",
              "| File | SHA256 | Rows |", "| --- | --- | ---: |",
              f"| `{registry.release['archive']['file']}` | `{registry.release['archive']['sha256']}` | |",
              f"| `{registry.release['note']['file']}` | `{registry.release['note']['sha256']}` | |"]
    for m in registry.members:
        lines.append(f"| `{m['file']}` | `{m['sha256']}` | {m['rows']:,} |")
    lines += ["", "Reference lists of data zones:", ""]
    for vintage, spec in registry.datazone_lists.items():
        lines.append(f"- {vintage}: `{spec['file']}`, {spec['zones']:,} zones, SHA256 `{spec['sha256']}`, as pinned in {spec['pinned_in']}.")
    lines += ["", "## Attribution", ""] + [f"- {a}" for a in registry.attribution] + [""]
    return "\n".join(lines)


def main(argv=None) -> int:
    OUT.write_text(render())
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
